// Lee datos de localStorage con clave 'mep-ddc-planes', o inicializa si no existen
export function loadPlanesFromStorage() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      savePlanesToStorage(INITIAL_PLANES);
      return INITIAL_PLANES;
    }
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed;
    }
    savePlanesToStorage(INITIAL_PLANES);
    return INITIAL_PLANES;
  } catch (err) {
    console.error('Error al leer localStorage:', err);
    return INITIAL_PLANES;
  }
}

// Guarda datos en localStorage bajo la clave requerida
export function savePlanesToStorage(planes) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(planes));
  } catch (err) {
    console.error('Error al guardar en localStorage:', err);
  }
}
